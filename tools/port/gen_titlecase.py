"""Writes lib/engine/py/titlecase.js: the characters whose titlecase isn't their uppercase.

JS has toUpperCase but no titlecase; str.title() and str.capitalize() need it ('ǆ' → 'ǅ', 'ﬁ' → 'Fi').
Run with the CPython the port follows:  python -I tools/port/gen_titlecase.py
"""
import json
import sys
from pathlib import Path

table = {}
for cp in range(sys.maxunicode + 1):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if c.title() != c.upper():
        table[c] = c.title()
out = Path(__file__).resolve().parents[2] / "plugins/draw-diagram/skills/draw-diagram/scripts/lib/engine/py/titlecase.js"
out.write_text(
    f"// Generated by tools/port/gen_titlecase.py from CPython {sys.version.split()[0]}. Do not edit.\n"
    "// Characters whose titlecase differs from their uppercase.\n"
    f"export const TITLECASE = {json.dumps(table, ensure_ascii=True, separators=(',', ':'))};\n",
    encoding="utf-8",
)
print(f"{len(table)} characters -> {out}")
